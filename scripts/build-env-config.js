#!/usr/bin/env node
/**
 * Generates env-config.js from environment variables.
 * Run during CI/CD or local dev setup before deploying the static app.
 */
const fs = require('fs');
const path = require('path');

const OUT_FILE = path.join(__dirname, '..', 'env-config.js');

const url = process.env.SUPABASE_URL || '';
const key = process.env.SUPABASE_ANON_KEY || '';

if (!url || !key) {
  console.warn('[build-env-config] SUPABASE_URL or SUPABASE_ANON_KEY is missing; env-config.js will contain empty placeholders.');
}

const content = `// Auto-generated by scripts/build-env-config.js — do not edit manually.
window.ENV = window.ENV || {};
window.ENV.SUPABASE_URL = ${JSON.stringify(url)};
window.ENV.SUPABASE_ANON_KEY = ${JSON.stringify(key)};
`;

fs.writeFileSync(OUT_FILE, content, 'utf8');
console.log(`[build-env-config] Wrote ${OUT_FILE}`);
